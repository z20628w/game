const assert = require('node:assert/strict')
const { mkdir, writeFile } = require('node:fs/promises')
const { resolve, join } = require('node:path')
const { pathToFileURL } = require('node:url')
const { execFileSync } = require('node:child_process')
const { _electron } = require('playwright')
const { build } = require('esbuild')

// 真实 Chromium 解码与窗口切换测试；只启动工作区中的独立宿主。
;(async () => {
  const folder = resolve('.test-data/video-handoff')
  await mkdir(folder, { recursive: true })
  const clip = join(folder, 'motion.mp4')
  execFileSync(process.env.FFMPEG_PATH || 'ffmpeg', ['-y', '-v', 'error', '-f', 'lavfi', '-i', 'testsrc2=size=192x108:rate=30:duration=3', '-c:v', 'libx264', '-pix_fmt', 'yuv420p', '-movflags', '+faststart', clip], { windowsHide: true })
  await build({ entryPoints: ['src/player.ts'], outfile: join(folder, 'player.js'), bundle: true, platform: 'browser' })
  await build({ stdin: { contents: "export {applyBackground} from './src/background';export {configureBackgroundPolicy} from './src/background-policy'", resolveDir: process.cwd(), loader: 'ts' }, outfile: join(folder, 'background.cjs'), bundle: true, platform: 'node', external: ['electron', 'original-fs'] })
  const data = { name: '视频交接测试', source: 'test:cold', url: pathToFileURL(clip).href, kind: 'video', slot: 'cold', durationMs: 100, opacity: 100, fit: 'cover', preview: false, videoTimeline: { backgroundURL: pathToFileURL(clip).href, backgroundSource: 'asset:test-loop', loopEntrySeconds: .5, fit: 'cover', opacity: 35, matched: true } }
  await writeFile(join(folder, 'player.html'), `<!doctype html><html><body style="margin:0"><main id="scene" style="position:absolute;inset:0"></main><footer><span id="status"></span><button id="skip">跳过</button></footer><style>video{position:absolute;inset:0;width:100%;height:100%}</style><script>window.results={completed:0};window.testData=${JSON.stringify(data)};if(location.search.includes("custom")){delete testData.videoTimeline;testData.durationMs=700}if(location.search.includes("broken"))testData.url+=".missing";window.player={data:async()=>window.testData,ready:error=>{results.ready=true;results.error=error},failed:error=>{results.error=error},finished:()=>{results.completed++;results.completedAt=performance.now()},onPlay:callback=>window.play=()=>{results.startedAt=performance.now();callback()},onStatus:()=>{},onViewport:()=>{}};</script><script src="player.js"></script></body></html>`)
  await writeFile(join(folder, 'background.html'), '<!doctype html><html><body style="margin:0"><div id="root">独立测试页面</div></body></html>')
  await writeFile(join(folder, 'main.cjs'), `const {app,BrowserWindow}=require('electron');app.setPath('userData',${JSON.stringify(join(folder, 'profile'))});app.whenReady().then(()=>{for(const [name,x] of [['player',40],['background',450]]){const w=new BrowserWindow({x,y:60,width:380,height:300,skipTaskbar:true,webPreferences:{backgroundThrottling:false}});w.loadFile(__dirname+'/'+name+'.html')}});app.on('window-all-closed',()=>app.quit())`)
  const env = { ...process.env }; delete env.ELECTRON_RUN_AS_NODE
  const application = await _electron.launch({ executablePath: require('electron'), args: [join(folder, 'main.cjs')], env })
  try {
    await application.firstWindow()
    while (application.windows().length < 2) await new Promise(resolve => setTimeout(resolve, 50))
    const pages = application.windows()
    await Promise.all(pages.map(page => page.waitForURL(/\/(player|background)\.html$/)))
    const player = pages.find(page => page.url().endsWith('/player.html'))
    const background = pages.find(page => page !== player)
    await player.waitForFunction(() => window.results?.ready)
    assert.equal(await player.evaluate(() => window.results.error), undefined)
    await player.evaluate(() => window.play())
    await player.waitForTimeout(500)
    assert.equal(await player.evaluate(() => window.results.completed), 0, '内置成片不能被旧配置的 100ms 定时器截断')
    assert.equal(await player.locator('video').first().evaluate(video => video.playbackRate), 1, '不能通过加速或降速凑时长')
    await player.waitForFunction(() => window.results.completed === 1, undefined, { timeout: 8000 })
    assert.ok(await player.evaluate(() => window.results.completedAt - window.results.startedAt) >= 2700, '应播放到解码器真实 ended')
    const time = await player.locator('video').last().evaluate(video => video.currentTime)
    await player.waitForTimeout(350)
    assert.ok(await player.locator('video').last().evaluate(video => video.currentTime) > time + .15, '等待软件期间应接着播放循环背景')

    const { applyBackground, configureBackgroundPolicy } = require(join(folder, 'background.cjs'))
    configureBackgroundPolicy(require('electron'))
    const profile = { adapter: { kind: 'codex', executable: require('electron'), args: [], title: '', pagePrefix: '', selectors: ['#root'], capability: 'supported', evidence: [], files: [] }, background: { enabled: true, source: 'asset:test-loop', opacity: 35, fit: 'cover' } }
    const client = { call: async (_method, params) => ({ result: { value: await background.evaluate(expression => (0, eval)(expression), params.expression) } }) }
    await background.evaluate(() => document.documentElement.setAttribute('data-theme', 'light'))
    await applyBackground(client, profile, resolve('resources'), { assetPath: () => clip }, true)
    await background.evaluate(() => document.dispatchEvent(new Event('visibilitychange')))
    await background.waitForTimeout(250)
    const held = await background.evaluate(() => window.__launchCanvasBackground.status())
    assert.equal(held.held, true)
    assert.equal(held.motion.paused, true, 'visibilitychange 不能绕过交接 hold')
    assert.ok(held.motion.seconds < .05)
    const mismatch = await background.evaluate(() => window.__launchCanvasBackground.prepareHandoff({ source: 'asset:other', seconds: 1, video: true }))
    assert.equal(mismatch.matched, false, '独立设置的不同背景不能误报同相位匹配')
    assert.equal(await background.evaluate(() => window.__launchCanvasBackground.status().motion.seconds), held.motion.seconds)
    const frame = await player.evaluate(() => window.__launchCanvasPlayerHandoff.prepare())
    const prepared = await background.evaluate(frame => window.__launchCanvasBackground.prepareHandoff(frame), frame)
    assert.equal(prepared.matched, true)
    assert.equal(prepared.backdrop, 'rgb(250, 248, 251)', '交接需读取实际浅色背景，不能固定淡入黑底')
    assert.ok(Math.abs(prepared.seconds - frame.seconds) < .034, '双方应定位到同一解码帧')
    const resumeAt = Date.now() + 180
    await background.evaluate(time => window.__launchCanvasBackground.resume(time), resumeAt)
    await player.evaluate(time => window.__launchCanvasPlayerHandoff.resumeAt(time), resumeAt)
    await player.waitForTimeout(380)
    const [playerTime, backgroundTime] = await Promise.all([player.locator('video').last().evaluate(video => video.currentTime), background.locator('video').evaluate(video => video.currentTime)])
    assert.ok(Math.abs(playerTime - backgroundTime) < .12, '两窗口应从同一相位继续播放')
    await player.evaluate(backdrop => window.__launchCanvasPlayerHandoff.reveal(120, backdrop), prepared.backdrop)
    await player.waitForTimeout(180)
    assert.equal(await player.locator('video').last().evaluate(video => Number(getComputedStyle(video).opacity)), .35)
    assert.equal(await player.evaluate(() => getComputedStyle(document.body).backgroundColor), prepared.backdrop)
    await background.evaluate(() => { window.retainedVideo = document.querySelector('video'); window.retainedTime = retainedVideo.currentTime })
    await applyBackground(client, profile, resolve('resources'), { assetPath: () => clip })
    assert.equal(await background.evaluate(() => document.querySelector('video') === window.retainedVideo), true, '直接置前且配置未改时应复用原背景视频')
    assert.ok(await background.evaluate(() => document.querySelector('video').currentTime >= window.retainedTime), '重复置前不能把背景时间线归零')
    profile.background.opacity = 36
    await applyBackground(client, profile, resolve('resources'), { assetPath: () => clip })
    assert.equal(await background.evaluate(() => document.querySelector('video') === window.retainedVideo), false, '用户修改配置时仍应立即应用新背景设置')
    assert.equal(await background.locator('video').evaluate(video => Number(getComputedStyle(video).opacity)), .36)
    await background.evaluate(() => document.querySelector('video').dispatchEvent(new Event('error')))
    const interrupted = await background.evaluate(() => window.__launchCanvasBackground.status())
    assert.equal(interrupted.ready, false, '运行中解码出错不能继续标记背景就绪')
    assert.match(interrupted.error, /播放中断/)
    await applyBackground(client, profile, resolve('resources'), { assetPath: () => clip })
    assert.equal(await background.evaluate(() => window.__launchCanvasBackground.status().ready), true, '下一次置前应重试已失败的背景')
    await background.evaluate(() => window.__launchCanvasBackground.dispose())
    assert.equal(await background.locator('video').count(), 0)
    assert.equal(await background.evaluate(() => !!window.__launchCanvasBackground), false)

    await player.goto(pathToFileURL(join(folder, 'player.html')).href + '?custom')
    await player.waitForFunction(() => window.results?.ready)
    await player.evaluate(() => window.play())
    await player.waitForFunction(() => window.results.completed === 1)
    const custom = await player.evaluate(() => ({ duration: results.completedAt - results.startedAt, rate: document.querySelector('video').playbackRate }))
    assert.equal(custom.rate, 1)
    assert.ok(custom.duration >= 600 && custom.duration < 1200, '自定义长视频保留用户裁切时长，不继承内置成片时长')
    await player.goto(pathToFileURL(join(folder, 'player.html')).href)
    await player.waitForFunction(() => window.results?.ready)
    await player.evaluate(() => { window.play(); document.querySelector('#skip').click() })
    await player.waitForFunction(() => window.results.completed === 1)
    const skipped = await player.locator('video').last().evaluate(video => ({ ready: video.readyState, visibility: getComputedStyle(video).visibility, paused: video.paused }))
    assert.ok(skipped.ready >= 2)
    assert.equal(skipped.visibility, 'visible')
    assert.equal(skipped.paused, false, '跳过动画也必须落在可播放背景上')
    await player.goto(pathToFileURL(join(folder, 'player.html')).href + '?broken')
    await player.waitForFunction(() => window.results?.ready)
    assert.match(await player.evaluate(() => window.results.error), /无法解码/)
    assert.equal(await player.evaluate(() => window.results.completed), 0, '损坏文件应明确失败，不能冒充播放完成')
    console.log('真实 MP4：原速完整播放、循环等待、hold、同相位恢复、独立背景、用户裁切、跳过、损坏文件与资源释放通过。仅验证独立测试窗口。')
  } finally { await application.close() }
})().catch(error => { console.error(error); process.exitCode = 1 })


